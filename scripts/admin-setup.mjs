// Creates private/config.php (git-ignored) with a salted PBKDF2 hash of the admin password.
// Upload that file to <site>/admin/config.php on your PHP server. The password itself is never stored.
import { pbkdf2Sync, randomBytes } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";

const ITERATIONS = 200_000;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "private", "config.php");

function askHidden(question) {
  return new Promise((resolve) => {
    const rl = createInterface({ input: process.stdin, output: process.stdout, terminal: true });
    const write = rl._writeToOutput;
    rl._writeToOutput = (text) => { if (text.includes(question)) write.call(rl, text); };
    rl.question(question, (answer) => { rl.close(); process.stdout.write("\n"); resolve(answer); });
  });
}

const password = await askHidden("Admin password (min 10 characters): ");
if (password.length < 10) { console.error("Password is too short."); process.exit(1); }
if (password !== (await askHidden("Repeat password: "))) { console.error("Passwords do not match."); process.exit(1); }

const salt = randomBytes(16).toString("hex");
const hash = pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256").toString("hex");
await mkdir(dirname(out), { recursive: true });
await writeFile(out, `<?php\n// Generated by npm run admin:setup. Keep this file private.\nreturn ['salt' => '${salt}', 'hash' => '${hash}', 'iterations' => ${ITERATIONS}];\n`, { mode: 0o600 });
console.log(`Created ${out}\nUpload it to the server as admin/config.php (next to admin/api.php).`);
